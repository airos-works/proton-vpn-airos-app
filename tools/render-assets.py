#!/usr/bin/env python3
"""Renders the GTK app's SVG assets (flags, status and feature icons) to PNG
resources for the Haiku app and writes resources/Assets.rdef, which imports
them into the executable.

Flags are 48 x 32 pixels (24 x 16 at 2x); icons are 48 x 48. Monochrome icons
are stored as white masks; the app tints them with the panel text colour.

    python3 tools/render-assets.py [gtk-assets-dir]

Needs librsvg's and cairo's Python bindings (gi Rsvg 2.0, pycairo).
"""
import os
import sys

import cairo
import gi
gi.require_version('Rsvg', '2.0')
from gi.repository import Rsvg  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join(ROOT, '.upstream/proton-vpn-gtk-app/proton/vpn/app/gtk/assets/icons')
OUT = os.path.join(ROOT, 'resources/assets')

# name -> (svg relative path, width, height, tint)
ICONS = {
    'protected': ('connection-status/protected.svg', 48, 48, False),
    'unprotected': ('connection-status/unprotected.svg', 48, 48, False),
    'fastest': ('connection-status/fastest.svg', 48, 32, False),
    'active-port': ('connection-status/active-port.svg', 48, 48, False),
    'free-countries': ('connection-status/free-countries.svg', 112, 32, False),
    'p2p': ('servers/p2p.svg', 48, 48, True),
    'tor': ('servers/tor.svg', 48, 48, True),
    'secure-core': ('servers/secure-core.svg', 48, 48, True),
    'smart-routing': ('servers/smart-routing.svg', 48, 48, True),
    'streaming': ('servers/streaming.svg', 48, 48, True),
    'info': ('info.svg', 48, 48, True),
    'location': ('location.svg', 48, 48, True),
    'maintenance': ('maintenance-icon.svg', 48, 48, True),
    'copy': ('copy.svg', 48, 48, True),
    'state-connected': ('state-connected.svg', 64, 64, False),
    'state-disconnected': ('state-disconnected.svg', 64, 64, False),
    'state-error': ('state-error.svg', 64, 64, False),
    'logo': ('proton-vpn-logo.svg', 640, 0, False),
    'sign': ('proton-vpn-sign.svg', 128, 128, False),
}


def render(svg_path, width, height, out_path, tint):
    handle = Rsvg.Handle.new_from_file(svg_path)
    ok, w, h = handle.get_intrinsic_size_in_pixels()
    if not ok or w <= 0 or h <= 0:
        dims = handle.get_dimensions()
        w, h = dims.width, dims.height
    if height == 0:
        height = int(round(width * h / w))
    surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, width, height)
    context = cairo.Context(surface)
    viewport = Rsvg.Rectangle()
    viewport.x, viewport.y, viewport.width, viewport.height = 0, 0, width, height
    handle.render_document(context, viewport)
    surface.flush()
    if tint:
        # Keep the coverage only; the app supplies the colour.
        data = surface.get_data()
        for i in range(0, len(data), 4):
            alpha = data[i + 3]
            data[i] = data[i + 1] = data[i + 2] = alpha  # premultiplied white
        surface.mark_dirty()
    surface.write_to_png(out_path)


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    os.makedirs(os.path.join(OUT, 'flags'), exist_ok=True)
    os.makedirs(os.path.join(OUT, 'icons'), exist_ok=True)
    lines = ['// Generated by tools/render-assets.py from the Proton VPN GTK app\'s assets.',
             '// PNG resources looked up by name: "flag:<cc>" and "icon:<name>".', '']
    rid = 1000
    for name, (svg, width, height, tint) in sorted(ICONS.items()):
        out = os.path.join(OUT, 'icons', name + '.png')
        render(os.path.join(source, svg), width, height, out, tint)
        lines.append('resource(%d, "icon:%s") #\'PNG \' import "assets/icons/%s.png";'
                     % (rid, name, name))
        rid += 1
    # The wordmark is white (the GTK app is dark); light panels need dark text.
    source_logo = cairo.ImageSurface.create_from_png(os.path.join(OUT, 'icons', 'logo.png'))
    logo = cairo.ImageSurface(cairo.FORMAT_ARGB32, source_logo.get_width(), source_logo.get_height())
    painter = cairo.Context(logo)
    painter.set_source_surface(source_logo, 0, 0)
    painter.paint()
    logo.flush()
    data = logo.get_data()
    for i in range(0, len(data), 4):
        b, g, r, a = data[i], data[i + 1], data[i + 2], data[i + 3]
        if a and min(r, g, b) * 255 >= 235 * a:   # premultiplied near-white
            data[i], data[i + 1], data[i + 2] = (0x24 * a) // 255, (0x1b * a) // 255, (0x1c * a) // 255
    logo.mark_dirty()
    logo.write_to_png(os.path.join(OUT, 'icons', 'logo-dark.png'))
    lines.append('resource(%d, "icon:logo-dark") #\'PNG \' import "assets/icons/logo-dark.png";' % rid)
    rid += 1
    flags = sorted(f for f in os.listdir(os.path.join(source, 'flags')) if f.endswith('.svg'))
    rid = 2000
    for flag in flags:
        code = flag[:-4].lower()
        out = os.path.join(OUT, 'flags', code + '.png')
        render(os.path.join(source, 'flags', flag), 48, 32, out, False)
        lines.append('resource(%d, "flag:%s") #\'PNG \' import "assets/flags/%s.png";'
                     % (rid, code, code))
        rid += 1
    with open(os.path.join(ROOT, 'resources/Assets.rdef'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('%d icons, %d flags' % (len(ICONS), len(flags)))


main()
